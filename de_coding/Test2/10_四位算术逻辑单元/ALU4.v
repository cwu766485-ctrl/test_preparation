// ============================================================
// 第10题：4 位组合算术逻辑单元。OP=00 加法，01 减法，10 按位与，11 按位或。Y 保存低 4 位；加法时 C 是进位，减法时 C=1 表示无符号借位；Z=1 表示 Y 为零。组合逻辑先给 Y、C 默认值，再按 OP 覆盖，避免输出保持旧值而推断锁存器。
// ============================================================
module ALU4 (
    input  wire [3:0] A,
    input  wire [3:0] B,
    input  wire [1:0] OP,
    output reg  [3:0] Y,
    output reg        C,
    output wire       Z
);
    always @(*) begin
        Y = 4'd0;                         // 先给默认值，即使后面的分支不覆盖也不会形成锁存器
        C = 1'b0;
        case (OP)
            2'b00: {C, Y} = {1'b0, A} + {1'b0, B};   // 扩成 5 位运算，最高位 C 接收加法进位
            2'b01: {C, Y} = {1'b0, A} - {1'b0, B};   // 扩成 5 位运算，最高位 C=1 表示减法发生借位
            2'b10: Y = A & B;
            2'b11: Y = A | B;
            default: ;                    // 四种选择值已覆盖；保留 default 便于阅读和修改
        endcase
    end

    assign Z = (Y == 4'd0);
endmodule
