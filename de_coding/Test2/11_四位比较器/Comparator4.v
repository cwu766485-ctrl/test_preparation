// ============================================================
// 第11题：4 位无符号比较器。GT、EQ、LT 分别表示 A 大于、等于、小于 B；有效二进制输入下，三个输出恰好一个为 1。这里按无符号数比较；若题目要求有符号数，需修改端口类型或显式进行有符号转换。
// ============================================================
module Comparator4 (
    input  wire [3:0] A,
    input  wire [3:0] B,
    output wire       GT,
    output wire       EQ,
    output wire       LT
);
    assign GT = (A >  B);
    assign EQ = (A == B);
    assign LT = (A <  B);

    // 门级理解：笔试中可将比较展开为逐位同或和优先判断。
    // EQ 等于各位 A[i] 与 B[i] 同或结果的逻辑与。
    // GT 从最高位开始判断：若高位相同，才比较下一位；xi 表示第 i 位的同或结果。
endmodule
